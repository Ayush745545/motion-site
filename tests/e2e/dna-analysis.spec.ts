import { expect, test } from "./account-fixture";

test("real website analysis is persisted and displayed on desktop and mobile", async ({ page }) => {
  test.skip(process.env.DNA_LIVE_TESTS !== "1", "Requires Docker, PostgreSQL and public internet; run pnpm test:dna:e2e");
  test.setTimeout(90_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/create");
  await page.getByLabel("Project name", { exact: true }).fill("Public website analysis");
  await page.getByLabel("Website URL", { exact: true }).fill("https://example.com");
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page).toHaveURL(/\/studio\?project=/);
  const project = new URL(page.url()).searchParams.get("project");
  await page.goto(`/analysis?project=${project}`);
  await page.getByRole("button", { name: "Analyze website", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Brand palette", exact: true })).toBeVisible({ timeout: 65_000 });
  await expect(page.getByText("Computed CSS only. This is not a full analysis of JavaScript-driven motion.")).toBeVisible();
  await expect(page.locator(".dna-screenshot")).toBeVisible();
  await expect.poll(() => page.locator(".dna-screenshot").evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(1440);
  await page.screenshot({ path: ".cache/screenshots/phase3-analysis-desktop.png", fullPage: true });
  const jsonLink = await page.getByRole("link", { name: "Open JSON result" }).getAttribute("href");
  expect(jsonLink).toBeTruthy();
  const resultResponse = await page.request.get(jsonLink!);
  expect(resultResponse.ok()).toBe(true);
  expect((await resultResponse.json()).motion_scope).toBe("computed-css-only");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Brand palette", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: ".cache/screenshots/phase3-analysis-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("link", {name:"Generate video",exact:true}).click();
  await expect(page.getByLabel("Video DNA source")).toHaveValue("analysis");
  await expect(page.getByRole("button",{name:"Render MP4",exact:true})).toBeEnabled({timeout:20000});
  await page.getByLabel("Video frame", {exact:true}).fill("140");
  await page.getByLabel("Video frame", {exact:true}).press("Tab");
  await expect(page.locator(".motion-composition img")).toHaveAttribute("src", /^data:image\/png;base64,/);
  await page.goto(`/director?project=${project}`);
  await page.getByRole("button",{name:"Generate storyboard",exact:true}).click();
  await expect(page.getByTestId("director-model")).toContainText("rules-v1");
  await page.getByLabel("reveal description",{exact:true}).fill("A deliberate source-backed interface reveal.");
  await page.getByLabel("reveal description",{exact:true}).press("Tab");
  await page.reload();
  await expect(page.getByLabel("reveal description",{exact:true})).toHaveValue("A deliberate source-backed interface reveal.");
  await page.getByRole("link",{name:"Open video studio",exact:true}).click();
  await expect(page.getByRole("button",{name:"Render MP4",exact:true})).toBeEnabled({timeout:20000});
  await page.getByLabel("Video frame",{exact:true}).fill("140");
  await page.getByLabel("Video frame",{exact:true}).press("Tab");
  await expect(page.locator(".motion-composition")).toContainText("A deliberate source-backed interface reveal.");
  const rejected = await page.request.post("/api/dna/analyze", { data: { url: "http://169.254.169.254/latest/meta-data" } });
  expect(rejected.status()).toBe(422);
  expect(errors).toEqual([]);
});
